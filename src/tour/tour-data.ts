export const STEP_FINAL_ID = 16;

export function getStepById(id: number): TourStepConfig | undefined {
  return TOUR_STEPS.find((s) => s.id === id);
}

export function getStepsForScreen(screen: Route): TourStepConfig[] {
  const ids = SCREEN_STEPS[screen];
  return TOUR_STEPS.filter((s) => ids.includes(s.id));
}
